/**
 * Run ledger — the evidence behind the 7-run gate.
 * ─────────────────────────────────────────────────────────────────────────
 * Every gated crawl is appended here with its automatic verdict. A run
 * counts toward the gate only when the machine check passed AND a human
 * reviewed the output as useful. When GATE_THRESHOLD such runs exist, the
 * engine is cleared to be integrated into FounderOS.
 * ─────────────────────────────────────────────────────────────────────────
 */
import { readFile, rename, writeFile } from "node:fs/promises";

export const GATE_THRESHOLD = 7;
export const REVIEW_STATUSES = ["useful", "not-useful"];

export function emptyLedger() {
  return { version: 1, threshold: GATE_THRESHOLD, runs: [] };
}

export async function loadLedger(file) {
  let text;
  try {
    text = await readFile(file, "utf8");
  } catch {
    return emptyLedger();
  }
  const parsed = JSON.parse(text); // a corrupt ledger must fail loudly, never reset silently
  if (parsed?.version !== 1 || !Array.isArray(parsed.runs)) {
    throw new Error(`${file} is not a version-1 run ledger`);
  }
  return parsed;
}

export async function saveLedger(file, ledger) {
  const tmp = `${file}.tmp`;
  await writeFile(tmp, `${JSON.stringify(ledger, null, 2)}\n`, "utf8");
  await rename(tmp, file);
}

export function appendRun(ledger, run) {
  const id = `R${ledger.runs.length + 1}`;
  const entry = { id, ...run, review: { status: "pending", note: "", at: null } };
  ledger.runs.push(entry);
  return entry;
}

export function reviewRun(ledger, id, status, note = "", now = new Date()) {
  if (!REVIEW_STATUSES.includes(status)) {
    throw new Error(`review must be one of: ${REVIEW_STATUSES.join(", ")}`);
  }
  const run = ledger.runs.find((r) => r.id === id);
  if (!run) throw new Error(`no run ${id} in the ledger`);
  run.review = { status, note, at: now.toISOString() };
  return run;
}

export function gateStatus(ledger) {
  const counted = ledger.runs.filter((r) => r.verdict === "pass" && r.review.status === "useful");
  return {
    threshold: ledger.threshold,
    counted: counted.length,
    awaitingReview: ledger.runs.filter((r) => r.verdict === "pass" && r.review.status === "pending").length,
    failed: ledger.runs.filter((r) => r.verdict === "fail").length,
    total: ledger.runs.length,
    competitors: [...new Set(counted.map((r) => r.competitor))].sort(),
    open: counted.length >= ledger.threshold,
  };
}

const modeLabel = (m) => (m.network ? "auth+network" : m.auth ? "auth" : "public");

export function renderMarkdown(ledger) {
  const s = gateStatus(ledger);
  const lines = [
    "# Crawler run ledger",
    "",
    "Generated by `gate/cli.mjs` — do not edit by hand; use `npm run gate:review`.",
    "",
    `**Gate:** ${s.counted} / ${s.threshold} counted runs ${s.open ? "— ✅ OPEN: cleared for FounderOS integration" : "— closed"}`,
    `· awaiting review: ${s.awaitingReview} · failed: ${s.failed} · competitors counted: ${s.competitors.join(", ") || "none"}`,
    "",
    "| Run | Competitor | Mode | Started | Duration | Exit | Verdict | Review | Notes |",
    "|---|---|---|---|---|---|---|---|---|",
  ];
  for (const r of ledger.runs) {
    const notes = r.verdict === "fail" ? r.reasons.join("; ") : r.review.note;
    lines.push(
      `| ${r.id} | ${r.competitor} | ${modeLabel(r.mode)} | ${r.startedAt} | ${r.durationSec}s | ${r.exitCode} | ${r.verdict} | ${r.review.status} | ${notes.replace(/\|/g, "/")} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Freelance Studio — contracts.
 * A Listing is a sellable project (AI system, app, web app, ecommerce build)
 * the founder packages and posts to marketplaces (Gumroad, Contra, Fiverr).
 * The UI and API share these shapes; they mirror the `listings` collection.
 */
export type ListingKind = "ai" | "system" | "app" | "web" | "ecommerce";
export type ListingPlatform = "gumroad" | "contra" | "fiverr";

export const LISTING_KINDS: Array<{ id: ListingKind; label: string }> = [
  { id: "ai", label: "AI Project" },
  { id: "system", label: "System" },
  { id: "app", label: "App" },
  { id: "web", label: "Web Application" },
  { id: "ecommerce", label: "Ecommerce" },
];

export const LISTING_PLATFORMS: Array<{ id: ListingPlatform; label: string }> = [
  { id: "gumroad", label: "Gumroad" },
  { id: "contra", label: "Contra" },
  { id: "fiverr", label: "Fiverr" },
];

export interface Listing {
  id: string;
  title: string;
  kind: ListingKind;
  /** The selling pitch — what a buyer/client reads. */
  pitch: string;
  priceUsd: number;
  /** Marketplaces this listing targets. */
  platforms: ListingPlatform[];
  /** Where it's actually live: platform → ISO date it was posted. */
  posted: Partial<Record<ListingPlatform, string>>;
  status: "draft" | "posted";
  createdAt: string;
  updatedAt: string;
}

export interface CreateListingInput {
  title: string;
  kind: ListingKind;
  pitch: string;
  priceUsd?: number;
  platforms: ListingPlatform[];
}

/** An idea surfaced by the Idea Agent — scored, transparent, actionable. */
export interface ProjectIdea {
  id: string;
  title: string;
  oneLiner: string;
  kind: ListingKind;
  scores: { demand: number; effort: number; fit: number; monetization: number };
  /** Weighted total 0–10 (demand + monetization heavy, effort inverted). */
  total: number;
  suggestedPriceUsd: number;
  platforms: ListingPlatform[];
  rationale: string;
  /** "model" = generated by the routed AI; "offline" = local template seed. */
  source: "model" | "offline";
}
